-- Logical owner: game-server
-- Compatibility phase: expand
-- Irreversible risk: none
-- Transaction: required
-- Lock timeout: 5s
-- Statement timeout: 60s
-- Backup point: not-required
-- Recovery command: SQLx rolls back the transaction; correct the migration and rerun db up.

-- Activity configuration is independent from CharacterProgressTable.csv and task progress.
-- Published versions and their configuration children are immutable snapshots.
CREATE TABLE IF NOT EXISTS activity (
  activity_id varchar(64) PRIMARY KEY,
  activity_key varchar(128) NOT NULL UNIQUE,
  activity_type varchar(64) NOT NULL,
  scope varchar(16) NOT NULL DEFAULT 'character',
  status varchar(16) NOT NULL DEFAULT 'draft',
  start_at timestamptz NOT NULL,
  end_at timestamptz NOT NULL,
  claim_deadline timestamptz NOT NULL,
  timezone varchar(64) NOT NULL,
  show_before_start boolean NOT NULL DEFAULT false,
  claim_mode varchar(32) NOT NULL DEFAULT 'manual',
  current_version integer NULL,
  created_by varchar(128) NOT NULL,
  published_at timestamptz NULL,
  offlined_at timestamptz NULL,
  offline_reason varchar(512) NULL,
  created_at timestamptz NOT NULL DEFAULT current_timestamp,
  updated_at timestamptz NOT NULL DEFAULT current_timestamp,
  CONSTRAINT ck_activity_scope CHECK (scope IN ('character', 'account')),
  CONSTRAINT ck_activity_status CHECK (status IN ('draft', 'published', 'running', 'ended', 'offline', 'archived')),
  CONSTRAINT ck_activity_type CHECK (btrim(activity_type) <> ''),
  CONSTRAINT ck_activity_timezone CHECK (btrim(timezone) <> ''),
  CONSTRAINT ck_activity_window CHECK (start_at < end_at),
  CONSTRAINT ck_activity_claim_deadline CHECK (claim_deadline >= end_at),
  CONSTRAINT ck_activity_claim_mode CHECK (claim_mode IN ('manual', 'automatic'))
);

CREATE INDEX IF NOT EXISTS idx_activity_status_window
  ON activity (status, start_at, end_at);
CREATE INDEX IF NOT EXISTS idx_activity_type_status
  ON activity (activity_type, status);

