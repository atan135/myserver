  CONSTRAINT ck_activity_version_type_config CHECK (jsonb_typeof(type_config_json) = 'object'),
  CONSTRAINT ck_activity_version_digest CHECK (config_digest ~ '^sha256:[0-9a-f]{64}$'),
  CONSTRAINT ck_activity_version_timezone CHECK (btrim(timezone) <> ''),
